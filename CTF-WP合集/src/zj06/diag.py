"""diag.py —— 探查 gcd(9, phi) = 3 的结构：到底哪个素数上 9 不可逆"""
from math import gcd

p = 2925490712948356009205547798331037409204468852265154197929696123102317330847028997592576845375767951888373634075473448002921250636926630905567362014595493
q = 7964077988212602731598828926489143570796450850963162530397620970577507270219530635660167912693046701894468774510746807002256765035407708129322533385075411
phi = (p - 1) * (q - 1)

print("gcd(9, phi)   =", gcd(9, phi))
print("gcd(9, p-1)   =", gcd(9, p - 1), "   gcd(3, p-1) =", gcd(3, p - 1))
print("gcd(9, q-1)   =", gcd(9, q - 1), "   gcd(3, q-1) =", gcd(3, q - 1))
print("p mod 3 =", p % 3, "  q mod 3 =", q % 3)
print("p mod 9 =", p % 9, "  q mod 9 =", q % 9)

# 3^s || (p-1)
for name, v in (("p", p), ("q", q)):
    s, t = 0, v - 1
    while t % 3 == 0:
        t //= 3
        s += 1
    print(f"{name}-1 = 3^{s} * t   (t % 3 = {t % 3})")

print("=> #solutions of x^9 = c mod n  =",
      gcd(9, p - 1) * gcd(9, q - 1))
